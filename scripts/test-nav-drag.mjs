import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium,acknowledgeReleaseNotes} from './browser.mjs';
const out='.preview/nav-drag';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:412,height:915},hasTouch:true,isMobile:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));let n=0;
const check=(name,value)=>{assert.ok(value,name);console.log('PASS '+name);n++;};
const nav=name=>page.locator('nav').getByRole('button',{name,exact:true});
const settle=()=>page.waitForTimeout(800);
const box=()=>page.locator('.nav-glass-position').boundingBox();
const route=()=>page.evaluate(()=>location.hash);
const position=()=>page.locator('.nav-glass-position').getAttribute('data-active-index');
try{
  await acknowledgeReleaseNotes(page);await page.goto('http://127.0.0.1:5188/');
  await page.waitForFunction(()=>window.__LOS__?.useStore.getState().hydrated);
  await page.evaluate(()=>window.__LOS__.useStore.getState().patchSettings({onboarded:true,theme:'liquid-glass-wc',perf:'high',motion:true,glassBlur:true}));
  await settle();await nav('计时').click();await settle();
  check('底栏实际使用独立玻璃组件',await page.locator('.nav-glass-stage liquid-glass').evaluate(el=>!!el.shadowRoot.querySelector('.surface.rendered')&&getComputedStyle(el).visibility==='visible'));
  check('旧CSS玻璃不再叠加',await page.locator('.nav-glass-body').evaluate(el=>getComputedStyle(el).display==='none'));
  let r=await box(),x=r.x+r.width/2,y=r.y+r.height/2;
  await page.mouse.move(x,y);await page.mouse.down();
  // 形变随速度发生；应在移动中取样，不能在停下后等待再要求保持拉伸。
  let widest=null;
  for(let i=1;i<=6;i++){
    await page.mouse.move(x-r.width*.65*i/6,y);
    await page.waitForTimeout(8);
    const frame=await page.locator('.nav-glass-stage liquid-glass').boundingBox();
    if(!widest||frame.width>widest.width)widest=frame;
  }
  const dragged=await box();
  check('按住拖动时连续跟手',Math.abs(dragged.x-(r.x-r.width*.65))<3);
  check('未松手不切换页面',await route()==='#/timer');
  const stretched=await page.locator('.nav-glass-stage liquid-glass').boundingBox();
  check('真实透镜拖动时拉长并压扁',widest.width>r.width*1.1&&widest.height<r.height*.97);
  check('拉伸透镜仍覆盖跟手位置',dragged.x+dragged.width/2>stretched.x&&dragged.x+dragged.width/2<stretched.x+stretched.width);
  await page.screenshot({path:`${out}/dragging.png`});
  await page.mouse.up();await settle();
  check('松手吸附并切到目标',await route()==='#/goals'&&await position()==='1');
  const restored=await page.locator('.nav-glass-stage liquid-glass').boundingBox();
  check('松手回弹后恢复原尺寸',Math.abs(restored.width-r.width+4)<1&&Math.abs(restored.height-r.height)<1);
  await page.screenshot({path:`${out}/released.png`});
  const cdp=await page.context().newCDPSession(page);
  r=await box();x=r.x+r.width/2;y=r.y+r.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  for(let i=1;i<=8;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+r.width*2*i/8,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await settle();
  check('真实触屏手势跨两项切换到统计',await route()==='#/stats'&&await position()==='3');
  r=await box();x=r.x+r.width/2;y=r.y+r.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-r.width,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});await settle();
  check('取消触屏手势保持原页面',await route()==='#/stats'&&await position()==='3');
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x-r.width,y-110,{steps:10});await page.mouse.up();await settle();
  check('拖出底栏上下范围不误切页',await route()==='#/stats');
  await nav('首页').click();await settle();check('拖动后仍可正常点击',await route()==='#/');
  await nav('设置').press('Enter');await settle();check('键盘仍可切换',await route()==='#/settings');
  await page.goBack();await settle();check('浏览器返回同步选中入口',await position()==='0');
  await page.setViewportSize({width:320,height:568});await settle();
  r=await box();x=r.x+r.width/2;y=r.y+r.height/2;
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+r.width*4,y,{steps:20});await page.mouse.up();await settle();
  check('320像素窄屏可拖到最右入口',await route()==='#/settings'&&await position()==='4');
  check('全部玻璃不超六个上下文',await page.locator('liquid-glass').count()<=6);
  await page.emulateMedia({reducedMotion:'reduce'});await settle();
  r=await box();x=r.x+r.width/2;y=r.y+r.height/2;
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x-r.width*2,y,{steps:10});await page.mouse.up();await settle();
  check('减少动画仍可拖动切换',await route()==='#/timer');
  await page.evaluate(()=>window.__LOS__.useStore.getState().patchSettings({perf:'saver'}));await settle();
  check('省电模式释放底栏与页面WebGL',await page.locator('liquid-glass').count()===0);
  check('无运行时异常',errors.length===0);
  console.log(`${n}/${n} 通过`);
}finally{await browser.close();}
