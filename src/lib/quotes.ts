/* ---------------- 随机挑选 ---------------- */

const LAST_KEY = 'learning-os:last-quote';

/**
 * 同一「次打开」内保持稳定，避免切页时语句乱跳。
 * 模块级缓存正好对应「应用的一次运行」：重新打开应用才会重新选。
 */
let sessionQuote: Quote | null = null;
/** 上次挑选时用的是哪个候选池；池子变了就要重新挑 */
let sessionPoolKey = '';

export interface QuotePoolOptions {
  /** 用户自定义的语句 */
  custom?: string[];
  /** 是否把内置语句库也纳入；默认纳入 */
  useBuiltin?: boolean;
}

/** 把「内置（可选）+ 自定义」合成候选池 */
export function buildQuotePool(opts: QuotePoolOptions = {}): Quote[] {
  const custom = (opts.custom ?? [])
    .map((t) => t.trim())
    .filter((t) => t.length > 0)
    .slice(0, MAX_CUSTOM_QUOTES)
    // 自定义语句一律归为 plain：它们没有内置语句那套语气分类
    .map((text, i): Quote => ({ id: `custom:${i}`, tone: 'plain', text }));

  if (opts.useBuiltin === false) return custom;
  return [...custom, ...QUOTES];
}

/** 池子的指纹。用它判断「设置变了没有」，避免每次都重挑。 */
function poolKeyOf(pool: Quote[], opts: QuotePoolOptions): string {
  return `${opts.useBuiltin === false ? 'c' : 'cb'}#${pool.length}#${pool[0]?.id ?? ''}#${pool[pool.length - 1]?.id ?? ''}`;
}

function readLast(): string | null {
  try {
    return localStorage.getItem(LAST_KEY);
  } catch {
    return null;
  }
}

function writeLast(id: string) {
  try {
    localStorage.setItem(LAST_KEY, id);
  } catch {
    /* 忽略 */
  }
}

/**
 * 随机挑一句（同一次打开内稳定）。
 * ──────────────────────────────────────────────────────────────
 * 之前是按「日期」做种子的确定性挑选，一天之内永远是同一句；
 * 语句只有 32 条时还看不出来，扩到 322 条后如果还用日期种子，
 * 每句要将近一年才轮到一次，等于白扩。
 * 现在改为：每次打开应用随机取一条，并把上一条记在本地，
 * 避免连着两次看到同一句。
 *
 * 候选池变化（增删自定义语句、开关内置）时会重新挑 ——
 * 否则用户刚加了句子，界面上还是旧的那条，看起来像没生效。
 */
export function pickQuote(opts: QuotePoolOptions = {}): Quote {
  const pool = buildQuotePool(opts);
  const key = poolKeyOf(pool, opts);
  if (sessionQuote && key === sessionPoolKey) return sessionQuote;

  sessionPoolKey = key;

  if (pool.length === 0) {
    // 关掉内置又没加自定义时的兜底，不让首页空着
    sessionQuote = { id: 'fallback', tone: 'plain', text: '开始就好。' };
    return sessionQuote;
  }

  const last = readLast();
  let idx = Math.floor(Math.random() * pool.length);
  // 命中上一条就顺延一位，保证不连续重复
  if (pool[idx].id === last) idx = (idx + 1) % pool.length;

  sessionQuote = pool[idx];
  writeLast(sessionQuote.id);
  return sessionQuote;
}

/**
 * 手动换一句（「换一句」按钮用）。
 * 与 pickQuote 的区别：**一定**换到不同的下一条，而不是随机 ——
 * 随机换的时候连点两下很可能又抽回原来那条，看起来像按钮失灵。
 */
export function nextQuote(opts: QuotePoolOptions = {}): Quote {
  const pool = buildQuotePool(opts);
  if (pool.length === 0) return { id: 'fallback', tone: 'plain', text: '开始就好。' };
  if (pool.length === 1) return pool[0];

  const cur = sessionQuote?.id ?? readLast();
  const at = pool.findIndex((q) => q.id === cur);
  const next = pool[(at + 1 + pool.length) % pool.length];
  sessionQuote = next;
  sessionPoolKey = poolKeyOf(pool, opts);
  writeLast(next.id);
  return next;
}

